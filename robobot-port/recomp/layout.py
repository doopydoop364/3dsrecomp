"""Memory layout and identity of a title, read from its ExHeader (never typed by hand)."""
import os, struct
from dataclasses import dataclass


def _u32(b, o):
    return struct.unpack_from('<I', b, o)[0]


@dataclass(frozen=True)
class Layout:
    title_id: int
    name: str
    text_base: int      # address of .text
    text_used: int      # bytes of code actually present (ExHeader size field)
    text_size: int      # page-aligned size of the .text mapping
    rodata_base: int
    rodata_size: int    # page-aligned
    data_base: int
    data_size: int      # page-aligned
    bss_size: int
    stack_size: int
    code_compressed: bool

    @property
    def text_end(self):
        return self.text_base + self.text_used

    @property
    def ro_end(self):
        """End of read-only memory: everything below it can be read as a constant."""
        return self.data_base

    @property
    def rw_end(self):
        """End of .data + .bss, page-rounded."""
        return (self.data_base + self.data_size + self.bss_size + 0xFFF) & ~0xFFF

    @property
    def image_size(self):
        """Bytes of the decompressed code image on disk (text + rodata + data)."""
        return self.text_size + self.rodata_size + self.data_size

    @property
    def title_hex(self):
        return f'{self.title_id:016x}'


def read_layout(exheader_path):
    e = open(exheader_path, 'rb').read()
    if len(e) < 0x210:
        raise ValueError(f'{exheader_path}: ExHeader is too short')
    lay = Layout(
        title_id=struct.unpack_from('<Q', e, 0x200)[0],
        name=e[:8].rstrip(b'\0').decode('ascii', 'replace'),
        text_base=_u32(e, 0x10), text_used=_u32(e, 0x18), text_size=_u32(e, 0x14) << 12,
        rodata_base=_u32(e, 0x20), rodata_size=_u32(e, 0x24) << 12,
        data_base=_u32(e, 0x30), data_size=_u32(e, 0x34) << 12, bss_size=_u32(e, 0x3C),
        stack_size=_u32(e, 0x1C), code_compressed=bool(e[0xD] & 1))
    if lay.rodata_base != lay.text_base + lay.text_size or lay.data_base != lay.rodata_base + lay.rodata_size:
        raise ValueError('segments are not contiguous; this tool assumes .text, .rodata and .data follow each other')
    return lay


def write_layout_header(lay, path):
    """C header with the values the runtime needs at compile time."""
    with open(path, 'w') as fh:
        fh.write('/* generated by recomp/layout.py from the title\'s ExHeader; do not edit */\n#pragma once\n')
        fh.write(f'#define RECOMP_TITLE_ID      0x{lay.title_id:016x}ull\n')
        fh.write(f'#define RECOMP_TITLE_ID_LO   0x{lay.title_id & 0xFFFFFFFF:08x}u\n')
        fh.write(f'#define RECOMP_TITLE_ID_HI   0x{lay.title_id >> 32:08x}u\n')
        fh.write(f'#define RECOMP_TEXT_BASE     0x{lay.text_base:08x}u\n')
        fh.write(f'#define RECOMP_TEXT_SIZE     0x{lay.text_size:08x}u   /* page-aligned mapping */\n')
        fh.write(f'#define RECOMP_TEXT_USED     0x{lay.text_used:08x}u   /* bytes of code */\n')
        fh.write(f'#define RECOMP_RO_END        0x{lay.ro_end:08x}u\n')
        fh.write(f'#define RECOMP_RW_END        0x{lay.rw_end:08x}u\n')


def find_game_file(root, title_id):
    """Per-game hand-written settings: <root>/games/<title id>.toml, or None."""
    p = os.path.join(root, 'games', f'{title_id:016x}.toml')
    return p if os.path.exists(p) else None
